// Where the cloud lives. Baked into the build on purpose: a shopkeeper should
// never type a service URL, and support should never have to ask what someone
// pasted. Overridable by environment for development only.
const (
	defaultRelayURL   = "https://relay.example.com"
	defaultLLMURL     = "https://llm.example.com"
	defaultInvoiceURL = "https://invoice.example.com"
	defaultWebURL     = "https://web.example.com"
)

func settingOr(cfg map[string]string, key, fallback string) string {
	if v := strings.TrimSpace(cfg[key]); v != "" {
		return v
	}
	return fallback
}

// LoadCloudSettings reads the cloud configuration. Environment variables win,
// so a dev machine can point elsewhere without touching the database.
func LoadCloudSettings(db *sql.DB) map[string]string {
	out := map[string]string{}
	rows, err := db.Query(`SELECT key, value FROM settings
		WHERE key LIKE 'relay_%' OR key LIKE 'llm_%' OR key LIKE 'invoice_%'
		OR key LIKE 'web_%'`)
	if err != nil {
		return out
	}
	defer rows.Close()
	for rows.Next() {
		var k, v string
		if rows.Scan(&k, &v) == nil {
			out[k] = v
		}
	}
	return out
}

func relayBase(cfg map[string]string) string {
	return strings.TrimSuffix(settingOr(cfg, "relay_base", defaultRelayURL), "/")
}

// RelayBaseURL exposes the resolved relay address to the server bootstrap.
func RelayBaseURL(cfg map[string]string) string { return relayBase(cfg) }

func (s *Server) putSetting(key, value string) error {
	_, err := s.db.Exec(`INSERT INTO settings (key, value, updated_at) VALUES (?, ?, ?)
		ON CONFLICT (key) DO UPDATE SET value = excluded.value, updated_at = excluded.updated_at`,
		key, value, domain.NowISO())
	return err
}

// cloudStatus tells the app whether this shop is reachable from outside and
// where the services live. Secrets never leave the server.
func (s *Server) cloudStatus(w http.ResponseWriter, r *http.Request) {
	cfg := LoadCloudSettings(s.db)
	enrolled := cfg["relay_binding_id"] != "" && cfg["relay_token"] != ""
	writeJSON(w, http.StatusOK, map[string]any{
		"enrolled":        enrolled,
		"relay_enabled":   cfg["relay_enabled"] == "1",
		"relay_connected": relayConnected(),
		"relay_base":      relayBase(cfg),
		"relay_subdomain": cfg["relay_subdomain"],
		"llm_url":         settingOr(cfg, "llm_url", defaultLLMURL),
		"invoice_url":     settingOr(cfg, "invoice_url", defaultInvoiceURL),
		"web_url":         settingOr(cfg, "web_url", defaultWebURL),
	})
}

// reauth re-checks the caller's own password. Connecting the shop to the
// internet and pairing a phone are both "prove it's really you" moments.
func (s *Server) reauth(r *http.Request, password string) bool {
	u := authFrom(r)
	if u == nil || password == "" {
		return false
	}
	var hash string
	if err := s.db.QueryRow(`SELECT password_hash FROM users WHERE id = ?`, u.ID).
		Scan(&hash); err != nil {
		return false
	}
	return bcrypt.CompareHashAndPassword([]byte(hash), []byte(password)) == nil
}

// cloudConnect enrolls this shop with the relay (once) and switches remote
// access on. The shopkeeper sees a single button; the binding and token are
// generated by the relay and stored here, never shown.
func (s *Server) cloudConnect(w http.ResponseWriter, r *http.Request) {
	if !s.isAdmin(r) {
		forbid(w)
		return
	}
	var in struct {
		Password string `json:"password"`
	}
	if err := decode(r, &in); err != nil {
		writeErr(w, http.StatusBadRequest, err.Error())
		return
	}
	if !s.reauth(r, in.Password) {
		writeErr(w, http.StatusUnauthorized, "mot de passe incorrect")
		return
	}

	cfg := LoadCloudSettings(s.db)
	if cfg["relay_binding_id"] == "" || cfg["relay_token"] == "" {
		var shopName string
		s.db.QueryRow(`SELECT value FROM settings WHERE key='company_name'`).Scan(&shopName)

		body, _ := json.Marshal(map[string]string{"shop_name": shopName})
		req, err := http.NewRequest(http.MethodPost, relayBase(cfg)+"/enroll",
			bytes.NewReader(body))
		if err != nil {
			writeErr(w, http.StatusInternalServerError, err.Error())
			return
		}
		req.Header.Set("Content-Type", "application/json")
		req.Header.Set("User-Agent", "elixir-gestion/1.0")

		resp, err := (&http.Client{Timeout: 20 * time.Second}).Do(req)
		if err != nil {
			writeErr(w, http.StatusServiceUnavailable,
				"service cloud injoignable — vérifiez la connexion internet")
			return
		}
		defer resp.Body.Close()
		raw, _ := io.ReadAll(resp.Body)
		if resp.StatusCode >= 300 {
			writeErr(w, http.StatusBadGateway,
				"le service cloud a refusé l'inscription")
			return
		}
		var enrolled struct {
			BindingID string `json:"binding_id"`
			Token     string `json:"token"`
			Subdomain string `json:"subdomain"`
		}
		if json.Unmarshal(raw, &enrolled) != nil || enrolled.BindingID == "" {
			writeErr(w, http.StatusBadGateway, "réponse inattendue du service cloud")
			return
		}
		for k, v := range map[string]string{
			"relay_binding_id": enrolled.BindingID,
			"relay_token":      enrolled.Token,
			"relay_subdomain":  enrolled.Subdomain,
		} {
			if err := s.putSetting(k, v); err != nil {
				writeErr(w, http.StatusInternalServerError, err.Error())
				return
			}
		}
	}

	if err := s.putSetting("relay_enabled", "1"); err != nil {
		writeErr(w, http.StatusInternalServerError, err.Error())
		return
	}
	s.cloudStatus(w, r)
}

// cloudDisconnect stops the tunnel but keeps the binding, so reconnecting
// later does not strand paired phones on a dead subdomain.
func (s *Server) cloudDisconnect(w http.ResponseWriter, r *http.Request) {
	if !s.isAdmin(r) {
		forbid(w)
		return
	}
	if err := s.putSetting("relay_enabled", "0"); err != nil {
		writeErr(w, http.StatusInternalServerError, err.Error())
		return
	}
	s.cloudStatus(w, r)
}

// ---------------- Phone pairing ----------------

type pairingCode struct {
	userID  string
	expires time.Time
}

var (
	pairMu    sync.Mutex
	pairCodes = map[string]pairingCode{}
)

const pairTTL = 5 * time.Minute

// Unambiguous alphabet: no O/0, I/1, so a code read off a screen can't be
// mistyped into a support call.
const pairAlphabet = "ABCDEFGHJKMNPQRSTUVWXYZ23456789"

func newPairCode() string {
	b := make([]byte, 8)
	for i := range b {
		n, err := rand.Int(rand.Reader, big.NewInt(int64(len(pairAlphabet))))
		if err != nil {
			return ""
		}
		b[i] = pairAlphabet[n.Int64()]
	}
	return string(b)
}

func prunePairCodes() {
	now := time.Now()
	for k, v := range pairCodes {
		if now.After(v.expires) {
			delete(pairCodes, k)
		}
	}
}

// cloudPair mints a short-lived, single-use code for the QR shown on screen.
// The phone exchanges it for its own session, so the admin password is never
// typed into (or photographed from) a phone.
func (s *Server) cloudPair(w http.ResponseWriter, r *http.Request) {
	var in struct {
		Password string `json:"password"`
	}
	if err := decode(r, &in); err != nil {
		writeErr(w, http.StatusBadRequest, err.Error())
		return
	}
	if !s.reauth(r, in.Password) {
		writeErr(w, http.StatusUnauthorized, "mot de passe incorrect")
		return
	}

	cfg := LoadCloudSettings(s.db)
	if cfg["relay_subdomain"] == "" || cfg["relay_enabled"] != "1" {
		writeErr(w, http.StatusConflict,
			"connectez d'abord le magasin au cloud")
		return
	}

	code := newPairCode()
	if code == "" {
		writeErr(w, http.StatusInternalServerError, "génération du code impossible")
		return
	}
	u := authFrom(r)
	pairMu.Lock()
	prunePairCodes()
	pairCodes[code] = pairingCode{userID: u.ID, expires: time.Now().Add(pairTTL)}
	pairMu.Unlock()

	var shopName string
	s.db.QueryRow(`SELECT value FROM settings WHERE key='company_name'`).Scan(&shopName)

	// Everything the phone needs, in one QR.
	writeJSON(w, http.StatusOK, map[string]any{
		"code":       code,
		"expires_in": int(pairTTL.Seconds()),
		"payload": map[string]any{
			"v":     1,
			"relay": relayBase(cfg),
			"shop":  cfg["relay_subdomain"],
			"name":  shopName,
			"code":  code,
		},
	})
}

// pairExchange is called BY THE PHONE, through the relay, with no session yet:
// the code is the credential. It is single-use and expires in five minutes.
func (s *Server) pairExchange(w http.ResponseWriter, r *http.Request) {
	var in struct {
		Code   string `json:"code"`
		Device string `json:"device"`
	}
	if err := decode(r, &in); err != nil {
		writeErr(w, http.StatusBadRequest, err.Error())
		return
	}
	code := strings.ToUpper(strings.TrimSpace(in.Code))

	pairMu.Lock()
	prunePairCodes()
	entry, ok := pairCodes[code]
	if ok {
		delete(pairCodes, code) // single use
	}
	pairMu.Unlock()

	if !ok {
		writeErr(w, http.StatusUnauthorized, "code invalide ou expiré")
		return
	}
	u, err := s.loadAuthUser(entry.userID)
	if err != nil || !u.Active {
		writeErr(w, http.StatusUnauthorized, "compte indisponible")
		return
	}
	writeJSON(w, http.StatusOK, map[string]any{
		"token": s.makeToken(u.ID),
		"user":  u,
	})
}

// relayStateFn is set by the relay client so the UI can show a live indicator.
var relayStateFn func() bool

// SetRelayStateFn wires the relay client's liveness into the API.
func SetRelayStateFn(fn func() bool) { relayStateFn = fn }

func relayConnected() bool {
	if relayStateFn == nil {
		return false
	}
	return relayStateFn()
}
